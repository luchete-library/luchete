"""Hand-authored profile pixels for the six verified fan mascot designs.

Profiles face right; the matching left row uses the same rigid poses mirrored.
These are game turnarounds, not claims of previously published official art.
The Pen rig, native 64 px grid and 32/58 ground anchor match the front sprites.
"""


def foot(a, x, part, fill, edge, shade, small=False):
    with a.part(part):
        width=4 if small else 6
        a.p([(x,50),(x+3,50),(x+3,54),(x+width,55),(x+width,57),
             (x,57),(x-1,55)],fill,edge)
        a.l([(x+1,56),(x+width-1,56)],shade)


